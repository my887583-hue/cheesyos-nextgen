CREATE TABLE IF NOT EXISTS public.ready_inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ready_item_id BIGINT NOT NULL REFERENCES public.ready_inventory_items(id) ON DELETE RESTRICT,
    movement_type TEXT NOT NULL,
    quantity_delta NUMERIC(12,3) NOT NULL,
    stock_before NUMERIC(12,3) NOT NULL,
    stock_after NUMERIC(12,3) NOT NULL,
    source_type TEXT NOT NULL DEFAULT 'MANUAL',
    reason TEXT,
    created_by TEXT,
    client_request_id UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ready_inventory_movements_type_chk CHECK (movement_type IN ('OPENING', 'PURCHASE', 'ADJUSTMENT_IN', 'ADJUSTMENT_OUT')),
    CONSTRAINT ready_inventory_movements_source_chk CHECK (source_type IN ('MANUAL')),
    CONSTRAINT ready_inventory_movements_delta_nonzero_chk CHECK (quantity_delta <> 0),
    CONSTRAINT ready_inventory_movements_sign_chk CHECK (
        (movement_type IN ('OPENING', 'PURCHASE', 'ADJUSTMENT_IN') AND quantity_delta > 0)
        OR (movement_type = 'ADJUSTMENT_OUT' AND quantity_delta < 0)
    ),
    CONSTRAINT ready_inventory_movements_balance_chk CHECK (stock_after = stock_before + quantity_delta)
);

